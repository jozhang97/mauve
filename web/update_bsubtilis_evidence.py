"""Build B. subtilis reference evidence from a frozen assay table and DoriC shards.

Run with --doric /path/to/shards (generated by update_doric.py).
Optional --extract-xlsx re-extracts the 257 essential calls from Koo Table S3 A.
Original GenBank files and alignment coordinates are never modified.
"""
import argparse
from collections import defaultdict
import csv
import gzip
import hashlib
import io
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET
import zipfile

from Bio import SeqIO
from Bio.SeqFeature import ExactPosition

ROOT = Path(__file__).resolve().parent
DEMO = ROOT / 'demo/bsubtilis'
STATIC = ROOT / 'mauve_web/static'
TABLE = ROOT / 'data/essentiality/koo-2017-bsubtilis.tsv'
PUBLICATION = 'https://doi.org/10.1016/j.cels.2016.12.013'
TABLE_URL = 'https://ars.els-cdn.com/content/image/1-s2.0-S2405471216304471-mmc4.xlsx'
TABLE_XLSX_SHA256 = '19f6675eb07b8869a4a0fa74f43180600b5ef05a3fdce360694b504d5ed1754f'
ORIGIN_PUBLICATION = 'https://pubmed.ncbi.nlm.nih.gov/8918236/'


def extract_table(path):
    if hashlib.sha256(path.read_bytes()).hexdigest() != TABLE_XLSX_SHA256:
        raise ValueError('Unexpected Table S3 workbook checksum')
    ns = {'m': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}
    with zipfile.ZipFile(path) as archive:
        strings = [''.join(e.itertext()) for e in ET.fromstring(archive.read('xl/sharedStrings.xml'))]
        sheet = ET.fromstring(archive.read('xl/worksheets/sheet1.xml'))
    rows = []
    for row in sheet.findall('.//m:row', ns):
        values = {}
        for cell in row:
            value = cell.find('m:v', ns)
            if value is not None:
                values[re.sub(r'\d', '', cell.attrib['r'])] = strings[int(value.text)] if cell.get('t') == 's' else value.text
        if re.fullmatch(r'BSU\d+', values.get('A', '')):
            rows.append([values['A'], values['B'], 'essential'])
    if len(rows) != 257 or len({r[0] for r in rows}) != 257:
        raise ValueError('Expected 257 unique essential loci in Table S3 A')
    with TABLE.open('w') as output:
        writer = csv.writer(output, delimiter='\t', lineterminator='\n')
        writer.writerow(['locus_tag', 'gene', 'status'])
        writer.writerows(rows)


def read_genome(genome):
    raw = gzip.decompress((DEMO / genome['annotations']).read_bytes())
    if hashlib.sha256(raw).hexdigest() != genome['genbank_sha256']:
        raise ValueError('GenBank checksum mismatch')
    record = SeqIO.read(io.StringIO(raw.decode()), 'genbank')
    if hashlib.sha256(str(record.seq).upper().encode()).hexdigest() != genome['sequence_sha256']:
        raise ValueError('Chromosome checksum mismatch')
    return record


def essentiality(manifest):
    genome, = [g for g in manifest['genomes'] if g['strain'] == '168']
    record = read_genome(genome)
    features = defaultdict(list)
    for feature in record.features:
        if feature.type == 'CDS':
            for tag in feature.qualifiers.get('locus_tag', []):
                features[tag.replace('_', '')].append(feature)
    rows = list(csv.DictReader(TABLE.open(), delimiter='\t'))
    if len(rows) != 257 or len({r['locus_tag'] for r in rows}) != 257:
        raise ValueError('Expected 257 unique essential loci')
    sequences = defaultdict(list)
    for row in rows:
        if row['status'] != 'essential':
            raise ValueError('Only the published essential set is included')
        matches = features[row['locus_tag']]
        if len(matches) != 1:
            raise ValueError(f'Missing or ambiguous locus: {row}')
        feature = matches[0]
        if 'pseudo' in feature.qualifiers or 'pseudogene' in feature.qualifiers or any(
                not isinstance(p.start, ExactPosition) or not isinstance(p.end, ExactPosition) for p in feature.location.parts):
            raise ValueError(f'Unusable CDS: {row}')
        sequence = str(feature.extract(record.seq)).upper()
        if set(sequence) - set('ACGT'):
            raise ValueError(f'Ambiguous sequence: {row}')
        sequences[hashlib.sha256(sequence.encode()).hexdigest()].append(row)
    return {'schema_version': 1, 'source': {
        'id': 'koo-2017-bsubtilis', 'title': 'Koo et al. (2017), Table S3 A: 257 essential genes',
        'publication': PUBLICATION, 'table_url': TABLE_URL,
        'strain': 'Bacillus subtilis 168', 'reference': record.id,
        'method': 'Genome-scale gene replacement with two antibiotic markers; published essential set only',
        'conditions': 'Growth in LB at 37 C. The study reports viable conditions or genetic contexts for 30 of these genes; see Table S3 A. Absence from this snapshot does not establish nonessentiality. Calls in other strains require identical complete CDS sequences and remain reference evidence.',
        'license': 'Factual locus identifiers and essential-set membership extracted from Table S3 A; article copyright Elsevier (2017).',
        'table_sha256': hashlib.sha256(TABLE.read_bytes()).hexdigest(),
        'source_xlsx_sha256': TABLE_XLSX_SHA256,
        'reference_sha256': genome['sequence_sha256'],
        'mapping': 'Unique BSU locus tag, ignoring underscore, to complete strain 168 reference CDS; exact CDS SHA-256 at runtime. Gene names are display labels only.',
        'input_rows': len(rows), 'counts': {'essential': len(rows)}},
        'sequences': dict(sorted(sequences.items()))}


def origins(manifest, shards):
    target = STATIC / 'doric-demo.json'
    snapshot = json.loads(target.read_text())
    for genome in manifest['genomes']:
        record = read_genome(genome)
        sequence = str(record.seq).upper()
        data = json.loads((shards / (hashlib.sha256(record.id.encode()).hexdigest()[:2] + '.json')).read_text())
        matches = []
        for region in data['records'].get(record.id, []):
            if region['length'] != len(record):
                continue
            # Some DoriC entries use an exclusive/zero-based start. Accept only
            # an exact region sequence at the reported start or one base later,
            # with the reported inclusive end unchanged; retain the correction.
            candidates = []
            for start in (region['start'], region['start'] + 1):
                end = region['end']
                actual = sequence[start - 1:end] if start <= end else sequence[start - 1:] + sequence[:end]
                if actual == region['sequence']:
                    candidates.append(start)
            if len(candidates) == 1:
                matches.append({**region, 'start': candidates[0], 'reported_start': region['start']})
        dna, = [f for f in record.features if f.type == 'CDS' and f.qualifiers.get('gene') == ['dnaA']]
        downstream = [r for r in matches if (r['start'] == int(dna.location.end) + 1 if dna.location.strand == 1 else r['end'] == int(dna.location.start))]
        if len(downstream) != 1:
            raise ValueError(f'Expected one verified downstream oriC2: {record.id}')
        selected = downstream[0]
        snapshot['records'][record.id] = [{
            'id': selected['id'], 'start': selected['start'], 'end': selected['end'],
            'length': len(record), 'sha256': genome['sequence_sha256'],
            'anchor': 'oriC2 region start', 'publication': ORIGIN_PUBLICATION,
            'note': 'Bipartite B. subtilis origin. Anchor is the start of the sequence-verified DoriC oriC2 region downstream of dnaA, not a resolved initiation nucleotide. Matching upstream regions are retained; regions crossing coordinate 1 wrap around the chromosome.',
            'regions': [{**{k: r[k] for k in ('id', 'start', 'end', 'reported_start')},
                         'sequence_sha256': hashlib.sha256(r['sequence'].encode()).hexdigest()} for r in matches],
            'source': data.get('source', 'https://tubic.org/doric/'),
        }]
    snapshot['bsubtilis_policy'] = {
        'publication': ORIGIN_PUBLICATION,
        'selection': 'One sequence-verified downstream oriC2 adjacent to dnaA. Exact accession, chromosome length and checksum required. Circular regions supported. A one-base start correction is accepted only when the entire DoriC region sequence matches and the end is unchanged; reported starts retained.'}
    target.write_text(json.dumps(snapshot, indent=2) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--doric', type=Path, required=True)
    parser.add_argument('--extract-xlsx', type=Path)
    args = parser.parse_args()
    if args.extract_xlsx:
        extract_table(args.extract_xlsx)
    manifest = json.loads((DEMO / 'manifest.json').read_text())
    evidence = essentiality(manifest)
    origins(manifest, args.doric)
    (STATIC / 'essentiality-bsubtilis.json').write_text(json.dumps(evidence, indent=2) + '\n')
    print(evidence['source']['counts'])
